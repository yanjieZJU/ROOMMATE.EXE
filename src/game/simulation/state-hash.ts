import type { DecisionSnapshot } from "../../shared/roommate-schemas";

function canonicalize(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(canonicalize);
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value as Record<string, unknown>)
        .filter(([key]) => key !== "stateHash")
        .sort(([left], [right]) => left.localeCompare(right))
        .map(([key, entry]) => [key, canonicalize(entry)]),
    );
  }
  return value;
}

export async function hashDecisionState(snapshot: DecisionSnapshot | Omit<DecisionSnapshot, "stateHash">): Promise<string> {
  const bytes = new TextEncoder().encode(JSON.stringify(canonicalize(snapshot)));
  const digest = await globalThis.crypto.subtle.digest("SHA-256", bytes);
  return Array.from(new Uint8Array(digest), (byte) => byte.toString(16).padStart(2, "0")).join("");
}
